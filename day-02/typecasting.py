#A conversion from one data type to another is called typecasting. In Python, we can convert one data type to another using built-in functions like int(), float(), str(), etc.
#Types of typecasting:
#1. Implicit Typecasting: In implicit typecasting, the Python interpreter automatically converts one
#2. Explicit Typecasting: In explicit typecasting, the programmer manually converts one data type to another using built-in functions.
a='1'
b='2'
print(int(a)+int(b))#explicit typecasting converting string into integer    